import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';

const VERSION = '0.8.2';
const SOURCE_URL = `https://unpkg.com/fflate@${ VERSION }/esm/browser.js`;
const OUT_DIR = 'examples/jsm/libs';

const args = process.argv.slice( 2 );

function argValue( name ) {

	const index = args.indexOf( name );
	return index === - 1 ? null : args[ index + 1 ];

}

function hasArg( name ) {

	return args.includes( name );

}

async function readSource() {

	const input = argValue( '--input' );
	const fflateSrc = argValue( '--fflate-src' );

	if ( input ) {

		return {
			path: resolve( input ),
			code: readFileSync( input, 'utf8' )
		};

	}

	if ( fflateSrc ) {

		const sourcePath = join( fflateSrc, 'esm/browser.js' );

		if ( ! existsSync( sourcePath ) ) {

			throw new Error( `Expected built fflate browser ESM at ${ sourcePath }. Run fflate's build first or pass --input.` );

		}

		return {
			path: resolve( sourcePath ),
			code: readFileSync( sourcePath, 'utf8' )
		};

	}

	const response = await fetch( SOURCE_URL );

	if ( ! response.ok ) {

		throw new Error( `Could not fetch ${ SOURCE_URL }: ${ response.status } ${ response.statusText }` );

	}

	return {
		path: SOURCE_URL,
		code: await response.text()
	};

}

function section( code, start, end ) {

	const startIndex = code.indexOf( start );

	if ( startIndex === - 1 ) {

		throw new Error( `Could not find start marker: ${ start }` );

	}

	const endIndex = code.indexOf( end, startIndex );

	if ( endIndex === - 1 ) {

		throw new Error( `Could not find end marker: ${ end }` );

	}

	return code.slice( startIndex, endIndex );

}

function stripExports( code ) {

	return code.replace( /^export /gm, '' );

}

function from( code, start ) {

	const startIndex = code.indexOf( start );

	if ( startIndex === - 1 ) {

		throw new Error( `Could not find start marker: ${ start }` );

	}

	return code.slice( startIndex );

}

function banner( sourcePath, name ) {

	const displaySourcePath = sourcePath.startsWith( 'http' ) ? sourcePath : relative( process.cwd(), sourcePath ) || sourcePath;

	return `/*!
fflate - fast JavaScript compression/decompression
<https://101arrowz.github.io/fflate>
Licensed under MIT. https://github.com/101arrowz/fflate/blob/master/LICENSE
version ${ VERSION }

This ${ name } entrypoint is generated by utils/vendor-fflate.js from:
${ displaySourcePath }
*/

`;

}

function writeGenerated( file, content ) {

	writeFileSync( join( OUT_DIR, file ), content );
	console.log( `Wrote ${ join( OUT_DIR, file ) }` );

}

